// Generates the Tailwind v3 preset (index.js / index.cjs) and the Tailwind v4 theme (theme.css)
// from the Material Glass tokens, so utilities like bg-primary or text-on-surface map to the live
// --mg-* variables and follow every theme, mode and glass preset.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, '../../tokens/material-glass.tokens.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));
const roles = Object.keys(tokens.themes['sea-glass'].light.color);
const shapes = Object.keys(tokens.shape);
const header = `/* GENERATED by packages/tailwind/build.mjs from Material Glass tokens. @material-glass/tailwind v${pkg.version} */`;

// ── Tailwind v3: preset + plugin ──
const colors = Object.fromEntries(roles.map((r) => [r, `rgb(var(--mg-${r}-rgb) / <alpha-value>)`]));
const radius = Object.fromEntries(shapes.map((s) => [s === 'full' ? 'full' : `mg-${s}`, `var(--mg-shape-${s})`]));
const glass = (tier) => ({
  '--_a': `var(--mg-glass-alpha-${tier})`,
  '--_blur': `var(--mg-glass-blur-${tier})`,
  position: 'relative',
  isolation: 'isolate',
  color: 'var(--mg-on-surface)',
  background: `linear-gradient(135deg, rgb(var(--mg-glass-base) / calc(var(--_a) + 0.08)), rgb(var(--mg-glass-base) / calc(var(--_a) - 0.12))), rgb(var(--mg-glass-tint) / var(--mg-glass-tint-alpha))`,
  '-webkit-backdrop-filter': 'blur(var(--_blur)) saturate(var(--mg-glass-saturate))',
  'backdrop-filter': 'blur(var(--_blur)) saturate(var(--mg-glass-saturate))',
  border: '1px solid rgb(255 255 255 / var(--mg-glass-rim))',
  'box-shadow': `inset 0 1px 0 rgb(255 255 255 / calc(${[0.35, 0.5, 0.65, 0.8, 0.9][tier]} * var(--mg-glass-specular))), 0 var(--mg-glass-shadow-y-${tier}) var(--mg-glass-shadow-blur-${tier}) rgb(var(--mg-shadow) / var(--mg-shadow-alpha))`
});
const v3 = {
  theme: {
    extend: {
      colors: { ...colors, 'glass-base': 'rgb(var(--mg-glass-base) / <alpha-value>)' },
      borderRadius: radius,
      fontFamily: { display: 'var(--mg-font-display)', body: 'var(--mg-font-body)', mono: 'var(--mg-font-mono)' },
      backdropBlur: Object.fromEntries([0, 1, 2, 3, 4].map((i) => [`glass-${i}`, `var(--mg-glass-blur-${i})`])),
      transitionTimingFunction: { spring: 'var(--mg-spring)', standard: 'var(--mg-motion-ease-standard)', emphasized: 'var(--mg-motion-ease-emphasized)' },
      transitionDuration: { short: 'var(--mg-motion-duration-short)', medium: 'var(--mg-motion-duration-medium)', long: 'var(--mg-motion-duration-long)', spring: 'var(--mg-spring-duration)' }
    }
  }
};
const glassUtilities = Object.fromEntries([0, 1, 2, 3, 4].map((i) => [`.glass-${i}`, glass(i)]));
const js = (cjs) => `${header}
// Tailwind's plugin() helper only wraps { handler }; building it directly avoids importing Tailwind here.
const plugin = (handler) => ({ handler });

const glassUtilities = ${JSON.stringify(glassUtilities, null, 2)};

/** Adds .glass-0 … .glass-4 and a liquid: variant (matches selected items: aria-current, aria-selected, aria-pressed). */
const materialGlassPlugin = plugin(({ addUtilities, addVariant }) => {
  addUtilities(glassUtilities);
  addVariant('liquid', ['&[aria-current]:not([aria-current="false"])', '&[aria-selected="true"]', '&[aria-pressed="true"]']);
  addVariant('glass-reduced', ['@media (prefers-reduced-transparency: reduce)', '[data-mg-transparency="reduced"] &']);
});

/** Tailwind v3 preset: colours, radii, fonts, blur and motion mapped to Material Glass variables. */
const preset = ${JSON.stringify(v3, null, 2).replace(/\n/g, '\n')};
preset.plugins = [materialGlassPlugin];

${cjs ? 'module.exports = preset;\nmodule.exports.default = preset;\nmodule.exports.materialGlassPlugin = materialGlassPlugin;' : 'export default preset;\nexport { materialGlassPlugin };'}
`;
writeFileSync(join(here, 'index.js'), js(false));
writeFileSync(join(here, 'index.cjs'), js(true));

// ── Tailwind v4: CSS-first theme ──
const css = [
  header,
  '/* Import after tailwindcss and material-glass.css:',
  '     @import "tailwindcss";',
  '     @import "material-glass/css";',
  '     @import "@material-glass/tailwind/theme.css";  */',
  '',
  '@theme inline {',
  ...roles.map((r) => `  --color-${r}: var(--mg-${r});`),
  ...shapes.filter((s) => s !== 'full').map((s) => `  --radius-mg-${s}: var(--mg-shape-${s});`),
  '  --font-display: var(--mg-font-display);',
  '  --font-body: var(--mg-font-body);',
  '  --ease-spring: var(--mg-spring);',
  '  --ease-standard: var(--mg-motion-ease-standard);',
  ...[0, 1, 2, 3, 4].map((i) => `  --blur-glass-${i}: var(--mg-glass-blur-${i});`),
  '}',
  '',
  ...[0, 1, 2, 3, 4].map((i) => {
    const g = glass(i);
    return `@utility glass-${i} {\n${Object.entries(g).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`;
  }),
  '',
  '@custom-variant liquid (&:is([aria-current]:not([aria-current="false"]), [aria-selected="true"], [aria-pressed="true"]));',
  '@custom-variant glass-reduced { @media (prefers-reduced-transparency: reduce) { @slot; } [data-mg-transparency="reduced"] & { @slot; } }',
  ''
].join('\n');
writeFileSync(join(here, 'theme.css'), css);
console.log(`@material-glass/tailwind: ${roles.length} colours, ${shapes.length} radii, 5 glass utilities (v3 preset + v4 theme)`);
